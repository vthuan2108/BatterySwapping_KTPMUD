let b={...a};Bms.step(a,1,60);Bms.step(b,60,1);assert(Math.abs(a.soc-b.soc)<0.001);assert.equal(a.soh,96);
console.log('PASS BMS charge, cutoff, full charge, time scale, stable SoH');
const pack=()=>({hasBattery:true,soc:20,soh:100,designCapacityAh:60,temperature:28,isLocked:false});
let hour=pack();Bms.step(hour,3600);
assert(Math.abs(hour.soc-45)<1e-9,'one hour at 15 A adds 15 Ah to a 60 Ah pack');
let delayed=pack();for(const seconds of [0.4,2.6,117,480,3000])Bms.step(delayed,seconds);
assert(Math.abs(delayed.soc-hour.soc)<1e-9,'variable elapsed ticks preserve all elapsed charge');
let stages={...pack(),designCapacityAh:30};let slices={...stages};
Bms.step(stages,7200);for(let i=0;i<7200;i++)Bms.step(slices,1);
assert(Math.abs(stages.soc-slices.soc)<1e-8,'long background delay integrates changing charging current');
assert(Math.abs(stages.temperature-slices.temperature)<1e-7,'thermal solver is independent of tick length');
