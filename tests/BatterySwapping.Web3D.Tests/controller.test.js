const assert = require('node:assert/strict');
const fs = require('node:fs');
const vm = require('node:vm');
const Bms = require('../../src/BatterySwapping.Web3D/js/bmsModel.js');
const sent=[];
function element(){return {dataset:{},style:{},classList:{toggle(){}},replaceChildren(){},setAttribute(){}};}
const elements={};
const context={URLSearchParams,location:{search:''},localStorage:{getItem(){return null;},setItem(){}},sessionStorage:{getItem(){return null;}},document:{getElementById(id){return elements[id]??=element();},createElement:element},MqttSync:{connected(){return true;},publish(...args){sent.push(args);}},BmsModel:Bms,CabinetModel:{setBatteryPresence(){},setBatteryEjected(){},setSlotLedColor(){},updateBatteryDisplay(){},setAlarmLight(){},getStation(){return null;}},ParticleSystem:{isOverheating(){return false;},stopOverheat(){}}};
